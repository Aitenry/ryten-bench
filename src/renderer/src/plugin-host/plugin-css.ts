import { pluginUrl } from '@shared/plugin/protocol'
import { sanitizePluginCss } from '@shared/plugin/css-safety'

/**
 * Injection and removal of **stylesheets shipped with a plugin** (`plugin://<id>/plugin.css`).
 *
 * Why this is needed (observed by the user, 2026-09-26: after installing an external plugin the UI
 * "looked completely deformed"): the host's own Tailwind generates CSS by scanning host sources at
 * **build time**, and plugin sources installed at runtime into `userData/plugins/<id>/` fall outside
 * that scan — measured, of the 124 class names used by task-planner / music-player, 49
 * (39% / 18%) had no rule at all in the host's output CSS; layout-critical classes such as
 * `w-[280px]` / `grid-cols-2` / `bottom-full` / `hover:scale-105` were all missing, so the layout
 * collapsed.
 *
 * The convention is therefore: **each plugin bundle ships a compiled `plugin.css`** (generated by
 * the plugin repository's build script with Tailwind scanning its own sources), and the host
 * injects it into `<head>` when loading the plugin and removes it on disable/uninstall. Plugins
 * thus do not depend on the host's scan scope, and third-party plugins stay self-contained.
 *
 * Details:
 * - Uses `fetch` + an inline `<style>` (`style-src 'self' 'unsafe-inline'` in the CSP allows it)
 *   instead of `<link rel="stylesheet" href="plugin://...">` (which would require
 *   `style-src plugin:`);
 * - **Silently skips** when the bundle has no `plugin.css` (old bundles, or plugins styled purely
 *   in JS), leaving only a debug log. This relies on the protocol handler reporting a missing file
 *   as an honest **404** (fixed 2026-09-26: it used to make net.fetch throw
 *   `ERR_FILE_NOT_FOUND`, so the `res.ok` check here was never reached and the main process logged
 *   a bogus warn with a stack on every run — noisy logs on every enable when an optional asset was
 *   missing);
 * - Re-injecting the same id removes the old node first (idempotent); after disable nothing is left
 *   behind in `document`.
 * - **Sanitized by the host guard before injection** (`@shared/plugin/css-safety`): `html` /
 *   `body` / `#root` / `*` / host shell class names are all dropped, and `:root` may only contain
 *   variables. A single `body { display:none }` can blank the whole app — styles are the easiest
 *   path for a plugin to affect the host, so they must be blocked at the entry point.
 *   Dropped rules produce a warn (with the original selector text) and are named in the acceptance
 *   report.
 */

const STYLE_ATTR = 'data-plugin-css'

/** Get the style node already injected for this plugin */
function existingStyle(id: string): HTMLStyleElement | null {
  return document.head.querySelector<HTMLStyleElement>(`style[${STYLE_ATTR}="${id}"]`)
}

/**
 * Inject a plugin's styles (no-op when there is no plugin.css).
 *
 * Failures are not thrown: missing styles should only mean "the UI looks off", and must not make
 * plugin loading fail (which would mean a blank screen).
 */
export async function installPluginCss(id: string): Promise<boolean> {
  removePluginCss(id)
  try {
    const res = await fetch(pluginUrl(id, 'plugin.css'))
    if (!res.ok) {
      console.debug(`[plugin:${id}] No plugin.css (HTTP ${res.status}), skipping style injection`)
      return false
    }
    const css = await res.text()
    if (css.trim() === '') return false
    let audit: ReturnType<typeof sanitizePluginCss>
    try {
      audit = sanitizePluginCss(css)
    } catch (err) {
      // If the sanitizer itself throws, **prefer not injecting** over putting unsanitized global
      // CSS into the host document
      console.warn(`[plugin:${id}] plugin.css sanitization failed, skipping style injection:`, err)
      return false
    }
    if (audit.dropped.length > 0 || audit.imports.length > 0) {
      const dropped = audit.dropped.slice(0, 6).join(' | ')
      console.warn(
        `[plugin:${id}] Dropped ${audit.dropped.length} global rules in plugin.css that would affect the host` +
          (audit.imports.length > 0 ? `, plus ${audit.imports.length} @import rules removed` : '') +
          (dropped ? `: ${dropped}${audit.dropped.length > 6 ? ' ...' : ''}` : '')
      )
    }
    if (audit.css.trim() === '') {
      console.warn(`[plugin:${id}] plugin.css is empty after sanitization (all global rules), no styles injected`)
      return false
    }
    const style = document.createElement('style')
    style.setAttribute(STYLE_ATTR, id)
    style.textContent = audit.css
    document.head.appendChild(style)
    console.info(
      `[plugin:${id}] Injected plugin styles plugin.css (${(audit.css.length / 1024).toFixed(1)}KB)`
    )
    return true
  } catch (err) {
    console.warn(`[plugin:${id}] Failed to inject plugin.css (ignored, does not affect plugin functionality):`, err)
    return false
  }
}

/** Remove a plugin's styles (disable/uninstall; idempotent) */
export function removePluginCss(id: string): void {
  existingStyle(id)?.remove()
}
