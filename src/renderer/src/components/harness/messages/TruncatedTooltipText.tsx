import React, { useEffect, useRef, useState } from 'react'
import { Tooltip } from 'antd'

/** Monospace digits: counters use monospace glyphs so the row does not jitter as the digit count changes */
export const MONO_FONT = "'JetBrains Mono', 'Cascadia Code', Consolas, 'Courier New', monospace"

/** Tool card text: single line + ellipsis on overflow, full content on hover (arrow-less Tooltip,
 *  shown only when overflowing).
 *
 *  Three easy-to-miss pitfalls are all handled here in one place:
 *  1. The ellipsis only works on a box that is block-level (or blockified) and width-constrained.
 *     This used to be an inline span, so overflow/text-overflow were completely ignored and
 *     clientWidth was always 0 → long text (the whole command of execute) broke out of the card and
 *     the hover tooltip also fired for short text. Hence the explicit display:block here, plus a
 *     1px tolerance.
 *  2. The shine must be applied to the single element that carries the text: when the outer
 *     ShinyText wraps the inner truncating span, the ellipsis stops working; and if the outer base
 *     color uses colorText, the base color and the highlight are almost the same in dark theme, so
 *     it looks like only the icon is glowing. Here shinyBaseColor (the same base color as
 *     ShinyIcon) + a pure white highlight stays clearly visible in both light and dark themes.
 *  3. **Layout properties must land on the Tooltip's outer box** (2026-09-27): callers always pass
 *     `flex: 1`, but it was written on the inner span — for the inner span `flex` means nothing (it
 *     is not in a flex container); what actually participates in the card's horizontal distribution
 *     is the **outer div** generated by Tooltip, which is block-level by default and takes the whole
 *     row. So the metadata/arrow on the right got pushed outside the card, and the main text was
 *     merely clipped by the card's `overflow: hidden` — whether the ellipsis appears depended
 *     entirely on the container, and another container (narrow sidebar, nested card) turned into
 *     "the text is pushed out". Now the outer box itself carries `flex: 1 1 auto; min-width: 0`,
 *     shrinks and distributes properly, and the ellipsis no longer relies on clipping as a fallback.
 */

/**
 * Callers often casually put `flex: 1` into `style` — that belongs to the outer box, and leaving
 * it on the inner span is meaningless (it may also override key properties of this component such
 * as `display`). Strip it explicitly here; `wrapperStyle` takes it over.
 */
const stripLayoutProps = (style?: React.CSSProperties): React.CSSProperties | undefined => {
  if (!style) return style
  const { flex, flexGrow, flexShrink, flexBasis, alignSelf, ...rest } = style
  void flex
  void flexGrow
  void flexShrink
  void flexBasis
  void alignSelf
  return rest
}

export const TruncatedTooltipText: React.FC<{
  text: string
  style?: React.CSSProperties
  /** Style of the outer box (the Tooltip container, i.e. the flex item in the card); put properties that participate in horizontal distribution here */
  wrapperStyle?: React.CSSProperties
  /** Shine base color (passing it enables the shine sweep; recommended to match the baseColor of the ShinyIcon in the same row) */
  shinyBaseColor?: string
  /** Shine highlight color, pure white by default (same as ShinyIcon's sweep color) */
  shinyShineColor?: string
}> = ({ text, style, wrapperStyle, shinyBaseColor, shinyShineColor = '#fff' }) => {
  const spanRef = useRef<HTMLSpanElement>(null)
  const [overflow, setOverflow] = useState(false)

  useEffect(() => {
    const el = spanRef.current
    if (!el) return
    const check = (): void => {
      setOverflow(el.scrollWidth > el.clientWidth + 1)
    }
    check()
    const observer = new ResizeObserver(check)
    observer.observe(el)
    return () => observer.disconnect()
  }, [text])

  return (
    <Tooltip title={overflow ? text : ''} arrow={false} styles={{ root: { maxWidth: 560 } }}>
      {/* Outer box: it carries both the flex item role and the width constraint for the ellipsis (see item 3 in the file header) */}
      <div
        data-truncated-text
        style={{
          flex: '1 1 auto',
          // A flex item without min-width: 0 will not shrink below its content width (so the ellipsis would never kick in)
          minWidth: 0,
          // Deliberately **no overflow: hidden**: clipping is left to the inner span; the outer box
          // keeps overflow visible so a popup mounted inside the box is never clipped
          ...wrapperStyle
        }}
      >
        <span
          ref={spanRef}
          className={shinyBaseColor ? 'shiny-text' : undefined}
          style={{
            // Override .shiny-text's display:inline-block — the ellipsis requires a block-level box
            display: 'block',
            whiteSpace: 'nowrap',
            overflow: 'hidden',
            textOverflow: 'ellipsis',
            minWidth: 0,
            ...(shinyBaseColor
              ? ({
                  '--shiny-base': shinyBaseColor,
                  '--shiny-shine': shinyShineColor
                } as React.CSSProperties)
              : null),
            ...stripLayoutProps(style)
          }}
        >
          {text}
        </span>
      </div>
    </Tooltip>
  )
}

export default TruncatedTooltipText
