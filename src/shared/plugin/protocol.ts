/**
 * Renderer → main process: report the host UI table's "key → export name" list (one-way send, no
 * return value).
 *
 * Why it is needed: the `@host/**` specifiers in a plugin renderer bundle are rewritten to
 * `plugin://host/ui.js?m=<key>`, and the bridge module is generated by the main process as ESM
 * from this list (`export const X = m["X"]`) — yet ESM named exports must be written out
 * statically, and the main process cannot reflect over the renderer's module namespace. The
 * renderer only needs to send it once at the earliest startup stage (`installHostUi()`, earlier
 * than any plugin renderer module is fetched).
 */
export const IPC_PLUGIN_HOST_UI_EXPORTS = 'plugin-host-ui-exports'

/**
 * Renderer → main process: query **which file** the currently loaded plugins came from
 * (read-only diagnostics).
 *
 * Returns `{ id: { installed, source: 'package' | 'absent', file?: string } }`.
 */
export const IPC_PLUGINS_LOADED_FROM = 'plugins-loaded-from'

/** Prefix validation regex for external plugin channels (plugin:<namespace>:...; namespace allows letters, digits, . _ -) */
export const PLUGIN_CHANNEL_RE = /^plugin:[A-Za-z0-9._-]+:/

/** Extract the namespace from a channel name; returns null for non-plugin channels (note: the namespace excludes the id's leading `plugin.` segment) */
export function pluginIdFromChannel(channel: string): string | null {
  const m = /^plugin:([A-Za-z0-9._-]+):/.exec(channel)
  return m ? m[1] : null
}

/**
 * Parse the plugin id and relative path out of `plugin://<id>/<relPath>?<query>`.
 *
 * Uses URL parsing rather than a hand-written regex (fixed 2026-09-26): with a **query string**
 * form such as `plugin://host/ui.js?m=…`, `?m=…` is not part of the path, and the regex's
 * `(\/.*)?$` fails to match outright (`?` is not in the allowed set) → the protocol handler
 * reports "invalid URL" / "module not found" and the whole host UI bridge chain 404s. URL parsing
 * also handles the authority segment and percent-encoding along the way.
 */
export function parsePluginUrl(url: string): { id: string; relPath: string } | null {
  let parsed: URL
  try {
    parsed = new URL(url)
  } catch {
    return null
  }
  if (parsed.protocol !== 'plugin:') return null
  const id = parsed.hostname || parsed.pathname.replace(/^\/+/, '').split('/')[0] || ''
  if (!/^[A-Za-z0-9._-]+$/.test(id)) return null
  // In `plugin://<id>/a/b.js` the hostname is the id and the pathname is `/a/b.js`;
  // in `plugin:///<id>/a/b.js` (no authority) the id segment must be stripped from the pathname.
  const rawPath = parsed.hostname
    ? parsed.pathname
    : parsed.pathname.replace(new RegExp(`^/+${id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`), '')
  let relPath = rawPath
  try {
    relPath = decodeURIComponent(rawPath)
  } catch {
    // Invalid encoding: keep the original text (downstream treats it as a normal path)
  }
  return { id, relPath: relPath.replace(/^\/+/, '') }
}

/** Plugin file URL helper: plugin://<id>/<relPath> */
export function pluginUrl(id: string, relPath: string): string {
  return `plugin://${id}/${relPath.replace(/^\/+/, '')}`
}
