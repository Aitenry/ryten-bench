/**
 * Plugin system IPC channel constants + plugin:// URL helper + channel naming convention (shared
 * by all three processes).
 *
 * Channel naming convention:
 * - Plugin invoke channels: `plugin:<namespace>:<channel>`, where namespace = plugin id with the
 *   leading `plugin.` segment removed (plugin.demo → plugin:demo:*); the main process performs the
 *   authoritative validation and preload caches the allowlist;
 * - Main process → renderer event channels are named by the same rule (e.g.
 *   `plugin:demo:items-updated`); they enter the allowlist only after the plugin declares them via
 *   `ctx.registerEvent(...)` in the main process;
 * - **core's own channels are not part of this namespace** (flat names): core only keeps shell
 *   capabilities such as window-* / setting / provider-* / plugins-* / weather-*;
 * - Management channels use kebab-case (plugins-*), consistent with the main-process style.
 */

/** Main process → renderer: pushes the enabled plugin channel list (preload updates its local allowlist cache) */
export const IPC_PLUGIN_CHANNELS_UPDATED = 'plugin-channels-updated'

/**
 * Renderer → main process: **synchronously** fetch the current channel list once
 * (`ipcRenderer.sendSync`).
 *
 * Why it is needed: `IPC_PLUGIN_CHANNELS_UPDATED` is a push (re-sent on did-finish-load), but the
 * renderer's first subscription (the plugin Provider's useEffect) happens while page scripts are
 * executing — earlier than did-finish-load, so "subscribing to event channels on the first frame"
 * inevitably races with the allowlist not having arrived yet (at the time it showed up as
 * `window.api.plugin.on` throwing "plugin channel not enabled"; now subscribing only warns, but a
 * missing allowlist still produces meaningless warnings). preload fetches the authoritative list
 * once over synchronous IPC at startup, after which incremental refreshes still come from the push.
 */
export const IPC_PLUGIN_CHANNELS_SYNC = 'plugin-channels-sync'

/**
 * Renderer → main process: **synchronously** fetch the enabled plugin list once
 * (`ipcRenderer.sendSync`).
 *
 * Why it is needed: the renderer host must synchronously decide which plugins to load while it is
 * being constructed (the first frame needs both routes and menus, and must not load plugins the
 * user disabled and then unload them — that would make the disabled plugins' Providers subscribe
 * to channels that do not exist). preload fetches the authoritative enabled state once over
 * synchronous IPC at startup, so the renderer can **load only enabled plugins from the start**.
 */
export const IPC_PLUGINS_LIST_SYNC = 'plugins-list-sync'

/** Main process → renderer: broadcasts plugin state after enable/disable/install/uninstall */
export const IPC_PLUGIN_STATE_CHANGED = 'plugin-state-changed'

