/// <reference types="vite/client" />

/**
 * **Text asset loader** for draft templates.
 *
 * Template bodies are no longer inlined as template strings in `templates.ts`; instead they live
 * under `template-files/` in the real draft layout, keeping their own extensions
 * (`.ts` / `.tsx` / `.mjs` / `.md`):
 *
 * ```
 * template-files/
 *   _shared/WORKSHOP.md          contract sheet (shared by all five templates; only the
 *                                "template / registered" two lines vary)
 *   _shared/main/context.ts      minimal type declarations for the host main-process context
 *   _shared/renderer/context.ts  minimal type declarations for the host renderer context
 *   full/...                     code of the complete skeleton
 *   page/ panel/ tool/ minimal/  the remaining templates
 * ```
 *
 * **Matched uniformly by path** (`import.meta.glob`, inlining the text into the main process
 * bundle at build time): for a given path `_shared` comes first and the template directory after
 * it (templates can override shared files); `plugin.json` is still generated by `manifestFile()`
 * (the manifest is data, not text).
 *
 * Placeholder syntax `${vars.<name>}`: only this prefix is substituted; `${...}` that generated
 * code carries itself and i18n `{{...}}` are kept as-is. A missing value throws immediately — a
 * failed draft creation is preferable to handing the model a half-finished source file full of
 * `${vars.xxx}`.
 */

const RAW_FILES = import.meta.glob('./template-files/**/*', {
  query: '?raw',
  import: 'default',
  eager: true
}) as Record<string, string>

const GLOB_PREFIX = './template-files/'
const TOKEN_RE = /\$\{vars\.([A-Za-z][A-Za-z0-9_]*)\}/g

/** One template file to render (`path` is the draft-relative path, POSIX separators) */
export interface TemplateFileSource {
  path: string
  body: string
}

/** Read text assets under a directory prefix as "relative path -> body" */
function filesUnder(prefix: string): Map<string, string> {
  const out = new Map<string, string>()
  for (const [key, body] of Object.entries(RAW_FILES)) {
    if (!key.startsWith(GLOB_PREFIX)) continue
    const rel = key.slice(GLOB_PREFIX.length)
    if (!rel.startsWith(`${prefix}/`)) continue
    out.set(rel.slice(prefix.length + 1), body)
  }
  return out
}

/** Substitute `${vars.<name>}`; an unknown placeholder throws immediately (a half-generated draft is harder to debug than a failure) */
function fillTokens(body: string, vars: Record<string, string>, file: string): string {
  return body.replace(TOKEN_RE, (whole, name: string) => {
    const value = vars[name]
    if (value === undefined) {
      throw new Error(`草稿模板占位符缺值：${whole}（文件 ${file}）`)
    }
    return value
  })
}

/**
 * Collect all text files of a template and sort them by path.
 *
 * `_shared` and `<template>` are merged with the latter overriding the former (currently no
 * same-named files; kept as an extension point); an empty template directory means the template
 * name is invalid — report an error instead of silently producing a draft with only shared files.
 */
export function renderTemplateFiles(
  template: string,
  vars: Record<string, string>
): TemplateFileSource[] {
  const shared = filesUnder('_shared')
  const own = filesUnder(template)
  if (own.size === 0) {
    throw new Error(`草稿模板 '${template}' 不存在：template-files/${template}/ 下没有任何文件`)
  }
  const merged = new Map<string, string>([...shared, ...own])
  return [...merged.entries()]
    .sort(([a], [b]) => a.localeCompare(b, 'en'))
    .map(([path, body]) => ({ path, body: fillTokens(body, vars, path) }))
}
