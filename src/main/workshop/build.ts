/**
 * Draft → installable plugin package.
 *
 * The output is **byte-for-byte isomorphic** to packages published in the plugin center (that
 * is exactly what lets "a plugin installed from the workshop" and "a plugin installed from the
 * plugin center" go through the very same load/unload/upgrade path):
 *
 * ```
 * dist/<id>/plugin.json     manifest (entry is written here)
 *           main.cjs        CJS: host capabilities obtained via globalThis.__RB_HOST_RESOLVE__
 *           renderer.mjs    ESM: host capabilities keep bare specifiers / `@host/**`, rewritten
 *                           to bridge URLs by the host loader
 *           chunk-*.mjs     lazy-loaded renderer chunks (specifiers absolutized to plugin://<id>/…)
 *           plugin.css      bundled stylesheet (auto: generated by Tailwind scanning sources;
 *                           file: the one in the draft)
 * ```
 *
 * Two easily hit pitfalls (both handled here):
 * 1. **The main-process side must really be rewritten**: `main.cjs` has no node_modules under
 *    `userData/plugins/<id>/`, so a bare require always fails → rewrite everything to
 *    `__RB_HOST_RESOLVE__("<spec>")` at bundle time;
 * 2. **Relative specifiers in the renderer must be absolutized**: the entry is fetched and
 *    imported as a blob, and blob modules have no relative base (`./chunk-x.mjs` resolves to
 *    `blob:…/chunk-x.mjs`).
 */

/** Third-party packages the renderer gets from the host vendor bridge (the host already holds the only instance, so a plugin bundle must not ship a second copy) */
export const RENDERER_VENDOR = [
  'react',
  'react-dom',
  'antd',
  '@remixicon/react',
  '@ant-design/icons',
  'dayjs'
]

/** Node built-in modules (including the `node:` prefix): kept external, resolved by Node itself at runtime */
const NODE_BUILTINS = new Set([...builtinModules, ...builtinModules.map((m) => `node:${m}`)])

/** Virtual module namespace: main-process specifiers land here; onLoad emits source that fetches from the host runtime */
const HOST_MODULE_NS = 'workshop-host'

/** Candidate main-process entry filenames (first existing one wins, in order) */
const MAIN_ENTRIES = ['main/index.ts', 'main/index.tsx', 'main/index.js', 'main/index.mjs']
/** Candidate renderer entry filenames */
const RENDERER_ENTRIES = [
  'renderer/plugin.tsx',
  'renderer/plugin.ts',
  'renderer/plugin.jsx',
  'renderer/plugin.js'
]

/** Main process: `module.exports = globalThis.__RB_HOST_RESOLVE__("<spec>")` (CJS output, ready to require) */
const cjsHostModule = (spec: string): string =>
  `module.exports = globalThis.__RB_HOST_RESOLVE__(${JSON.stringify(spec)});\n`

/** Collected specifiers (checked after the build to confirm the host really resolves them) */
interface SpecCollector {
  /** Specs that really go through __RB_HOST_RESOLVE__ in the main process */
  mainSpecs: Set<string>
  /** Host specs kept external in the renderer (`@host/**` and bare vendor modules) */
  rendererSpecs: Set<string>
}

const isAbsoluteSpec = (spec: string): boolean =>
  /^[A-Za-z]:[\\/]/.test(spec) || spec.startsWith('/')
const isBare = (spec: string): boolean =>
  !spec.startsWith('.') && !isAbsoluteSpec(spec) && !spec.startsWith('@host/')

/**
 * Bundle-time resolution of imports inside a plugin.
 *
 * - `@host/**` → main process: virtual module (fetched from the host runtime); renderer: **kept
 *   external** (rewritten by the host loader);
 * - Aliases `@shared/**` / `@renderer/**` (the convention used in repo sources) → mapped to
 *   `@host/shared/**` / `@host/renderer/**` so assistants can reference host capabilities in a
 *   familiar form;
 * - Renderer bare modules: in the vendor list → external; otherwise → **error with the allowed
 *   list** (the draft directory has no node_modules, so letting it through only becomes a
 *   context-free resolution failure at runtime);
 * - Main-process bare modules: virtual modules (resolved at runtime by the host against the app
 *   root, yielding the same instance) plus a post-build check;
 * - Relative/absolute paths: inside the draft they are bundled, outside the draft they are
 *   **rejected** (seeing no other directory also means no accidental reference to repo sources).
 */
function hostPlugin(side: 'main' | 'renderer', draftRoot: string, specs: SpecCollector): Plugin {
  return {
    name: 'workshop-host-runtime',
    setup(build) {
      build.onResolve({ filter: /.*/ }, (args) => {
        const spec = args.path

        if (NODE_BUILTINS.has(spec)) return { path: spec, external: true }
        if (spec.startsWith('plugin://')) return { path: spec, external: true }

        // Aliases: repo style → host keys
        let mapped = spec
        if (spec.startsWith('@shared/')) mapped = `@host/shared/${spec.slice('@shared/'.length)}`
        else if (spec.startsWith('@renderer/'))
          mapped = `@host/renderer/${spec.slice('@renderer/'.length)}`

        if (mapped.startsWith('@host/')) {
          if (side === 'renderer') {
            specs.rendererSpecs.add(mapped)
            return { path: mapped, external: true }
          }
          specs.mainSpecs.add(mapped)
          return { path: mapped, namespace: HOST_MODULE_NS }
        }

        if (isBare(spec)) {
          if (side === 'renderer') {
            const vendor = RENDERER_VENDOR.find((v) => spec === v || spec.startsWith(v + '/'))
            if (!vendor) {
              return {
                errors: [
                  {
                    text:
                      `插件不能依赖第三方包 '${spec}'（草稿目录里没有 node_modules）。` +
                      `渲染层只能用宿主已提供的：${RENDERER_VENDOR.join(' / ')}，` +
                      `以及 @host/renderer/** 的宿主 UI 模块。`
                  }
                ]
              }
            }
            specs.rendererSpecs.add(spec)
            return { path: spec, external: true }
          }
          specs.mainSpecs.add(spec)
          return { path: spec, namespace: HOST_MODULE_NS }
        }

        const from = args.importer ? path.dirname(args.importer) : draftRoot
        const abs = path.resolve(from, spec)
        const inside = abs === draftRoot || abs.startsWith(draftRoot + path.sep)
        if (!inside) {
          return {
            errors: [
              {
                text:
                  `导入越出草稿目录：'${spec}'（解析为 ${abs}）。` +
                  `插件只能引用草稿内的文件与 '@host/**' 宿主模块。`
              }
            ]
          }
        }
        return null
      })

      build.onLoad({ filter: /.*/, namespace: HOST_MODULE_NS }, (args) => ({
        contents: cjsHostModule(args.path),
        loader: 'js'
      }))
    }
  }
}

/** Find the entry file (returns null when none exists) */
function findEntry(draftRoot: string, candidates: string[]): string | null {
  for (const rel of candidates) {
    const abs = path.join(draftRoot, rel)
    if (fs.existsSync(abs)) return abs
  }
  return null
}

/** esbuild errors → human-readable multi-line text (with file:line:column) */
function formatEsbuildErrors(
  errors:
    | readonly { text: string; location?: { file?: string; line?: number; column?: number } }[]
    | undefined
): string[] {
  if (!errors || errors.length === 0) return []
  return errors.map((error) => {
    const loc = error.location
    const where = loc?.file
      ? `${path.basename(loc.file)}${loc.line ? `:${loc.line}${loc.column !== undefined ? `:${loc.column + 1}` : ''}` : ''}: `
      : ''
    return `${where}${error.text}`
  })
}

/**
 * Absolutize the **relative specifiers** in the multi-file renderer output to
 * `plugin://<id>/<file>` and return the number of rewrites.
 *
 * Same rule as the workshop's output rewriting: blob modules have no relative base.
 * Only rewrite relative specifiers that actually point to a file of this build (compared by
 * target filename) so string literals are not touched by mistake.
 */
export function absolutizeChunkSpecifiers(id: string, outDir: string): number {
  const emitted = new Set(fs.readdirSync(outDir).filter((f) => f.endsWith('.mjs')))
  const REL_SPEC =
    /(\bfrom\s*|\bimport\s*\(\s*|(?:^|[;}\n])\s*import\s*)(['"])(\.{1,2}\/[^'"]+)\2/gm
  let count = 0
  for (const file of emitted) {
    const full = path.join(outDir, file)
    const source = fs.readFileSync(full, 'utf-8')
    const next = source.replace(REL_SPEC, (whole, prefix: string, quote: string, spec: string) => {
      const target = path
        .relative(outDir, path.resolve(path.dirname(full), spec))
        .replace(/\\/g, '/')
      if (!emitted.has(target)) return whole
      count += 1
      return `${prefix}${quote}plugin://${id}/${target}${quote}`
    })
    if (next !== source) fs.writeFileSync(full, next)
  }
  return count
}

/** Host specifier → host UI bridge URL (key shape matches `external-loader.ts` / host-ui.ts) */
function bridgeUrlFor(spec: string): string | null {
  if (spec.startsWith('@host/')) {
    return `plugin://host/ui.js?m=${encodeURIComponent(spec)}`
  }
  if (RENDERER_VENDOR.some((v) => spec === v || spec.startsWith(v + '/'))) {
    return `plugin://host/ui.js?m=${encodeURIComponent(`@host/vendor/${spec}`)}`
  }
  return null
}

/**
 * Rewrite **all** host specifiers in the output to host UI bridge URLs (entry + every chunk)
 * and return the number of rewrites.
 *
 * Why this must happen at **build time** (verified on a real machine on 2026-09-27): the host's
 * `external-loader.ts` rewrites specifiers only when loading the entry, while lazy-loaded
 * chunks are fetched by the browser itself via `plugin://<id>/chunk-x.mjs` — there is no chance
 * to rewrite anything on that path, so a leftover `from "react"` in a chunk fails outright with
 * `Failed to resolve module specifier "react"`. Independently distributed plugin packages are
 * built the same way: the output only contains `plugin://host/ui.js?m=<key>`.
 */
export function rewriteHostSpecifiersInBundle(outDir: string): number {
  const SPEC_RE = /(\bfrom\s*|\bimport\s*\(\s*|(?:^|[;}\n])\s*import\s*)(['"])([^'"]+)\2/gm
  let count = 0
  for (const file of fs.readdirSync(outDir)) {
    if (!file.endsWith('.mjs')) continue
    const full = path.join(outDir, file)
    const source = fs.readFileSync(full, 'utf-8')
    const next = source.replace(SPEC_RE, (whole, prefix: string, quote: string, spec: string) => {
      const url = bridgeUrlFor(spec)
      if (!url) return whole
      count += 1
      return `${prefix}${quote}${url}${quote}`
    })
    if (next !== source) fs.writeFileSync(full, next)
  }
  return count
}

export interface BuildDraftOptions {
  /** dev: no minification + inline sourcemap (larger output but debuggable) */
  dev?: boolean
  /** Override the output directory (offline tooling uses a temp dir) */
  outDir?: string
}

export interface BuildDraftResult {
  info: WorkshopBuildInfo
  /** Normalized manifest (null when the build failed and the manifest is invalid) */
  manifest: Record<string, unknown> | null
}

/** Append a CSS chunk (empty chunks are ignored) */
function appendCss(parts: string[], chunk: string): void {
  const text = chunk.trim()
  if (text) parts.push(text)
}

/**
 * Build a draft.
 *
 * **Never throws**: every failure is collapsed into `info.ok === false` + `info.errors`, so the
 * assistant/panel gets a readable diagnosis (the tool layer then decides how to tell the model).
 *
 * **At most one build per draft at a time**: the build starts with `rm -rf dist/<id>`. The
 * sidebar and the workshop modal each keep their own `busyId`, so triggering a build from both
 * sides at once (or a model tool colliding with a user action) would delete the same output
 * directory twice and write mixed chunks. A second request just gets the first one's Promise and
 * the same result.
 */
const buildLocks = new Map<string, Promise<BuildDraftResult>>()

export function buildDraft(id: string, opts: BuildDraftOptions = {}): Promise<BuildDraftResult> {
  const running = buildLocks.get(id)
  if (running) return running
  const task = buildDraftInner(id, opts).finally(() => {
    buildLocks.delete(id)
  })
  buildLocks.set(id, task)
  return task
}

async function buildDraftInner(
  id: string,
  opts: BuildDraftOptions = {}
): Promise<BuildDraftResult> {
  const startedAt = Date.now()
  const info: WorkshopBuildInfo = {
    ok: false,
    durationMs: 0,
    files: [],
    errors: [],
    warnings: []
  }
  /** Manifest (available before and after the build; returned to the caller for static checks on failure) */
  let manifest: Record<string, unknown> | null = null

  const finish = (): BuildDraftResult => {
    info.durationMs = Date.now() - startedAt
    return { info, manifest }
  }

  if (!isWorkshopConfigured()) {
    info.errors.push('插件工坊尚未接线，无法构建')
    return finish()
  }

  const draftRoot = draftDir(id)
  if (!fs.existsSync(draftRoot)) {
    info.errors.push(`草稿 '${id}' 不存在（先 plugin_draft create 生成骨架）`)
    return finish()
  }

  const raw = readJson<Record<string, unknown>>(path.join(draftRoot, 'plugin.json'))
  if (!raw || typeof raw !== 'object') {
    info.errors.push('plugin.json 缺失或不是合法 JSON')
    return finish()
  }
  manifest = raw
  if (raw.id !== id) {
    info.errors.push(`plugin.json 的 id (${String(raw.id)}) 与草稿目录名 (${id}) 不一致`)
    return finish()
  }

  const meta = readDraftMeta(id)
  const cssMode: WorkshopCssMode = meta?.css ?? 'auto'
  const outDir = opts.outDir ?? distDir(id)
  const host = workshopHostOrNull()
  const specs: SpecCollector = { mainSpecs: new Set(), rendererSpecs: new Set() }

  /**
   * The source fingerprint is computed **before** the build: the output records "the sources
   * read for this build". If someone edits a file during the build, `isBuildStale` recomputes
   * and finds the mismatch — which is correct.
   */
  let sourceHash: string
  try {
    sourceHash = draftSourceHash(id, cssMode)
  } catch (err) {
    info.errors.push(`读取草稿源码失败：${(err as Error).message}`)
    return finish()
  }

  // Rebuild the output directory every time: leftover old chunks would make an installed plugin
  // still show the old UI
  fs.rmSync(outDir, { recursive: true, force: true })
  fs.mkdirSync(outDir, { recursive: true })

  const esbuild = host?.loader.require('esbuild') as typeof import('esbuild') | undefined
  if (!esbuild || typeof esbuild.build !== 'function') {
    info.errors.push(
      '构建器不可用：宿主里没有可用的 esbuild（打包后的应用需要把 esbuild 放进 dependencies 并 asarUnpack）'
    )
    return finish()
  }

  const rendererEntry = findEntry(draftRoot, RENDERER_ENTRIES)
  if (!rendererEntry) {
    info.errors.push(
      `缺少渲染层入口：需要 ${RENDERER_ENTRIES[0]}（导出 default { install(ctx) }）—— 插件包必须带渲染层入口`
    )
    return finish()
  }

  // ── ① Main process (emit a shell even without a main entry: the package contract requires main.cjs) ──
  const mainEntry = findEntry(draftRoot, MAIN_ENTRIES)
  try {
    const shared = {
      bundle: true,
      platform: 'node' as const,
      format: 'cjs' as const,
      target: 'node20',
      plugins: [hostPlugin('main', draftRoot, specs)],
      minify: !opts.dev,
      sourcemap: opts.dev ? ('inline' as const) : false,
      logLevel: 'silent' as const,
      legalComments: 'none' as const
    }
    if (mainEntry) {
      await esbuild.build({
        ...shared,
        entryPoints: [mainEntry],
        outfile: path.join(outDir, 'main.cjs')
      })
    } else {
      await esbuild.build({
        ...shared,
        stdin: {
          contents:
            '/** 本插件没有主进程代码（草稿里没有 main/index.ts）：空 install 满足包契约。 */\n' +
            'exports.install = function install() {}\n',
          resolveDir: draftRoot,
          sourcefile: 'main-stub.cjs',
          loader: 'js'
        },
        outfile: path.join(outDir, 'main.cjs')
      })
    }
  } catch (err) {
    info.errors.push(...formatEsbuildErrors((err as { errors?: never[] }).errors))
    if (info.errors.length === 0) info.errors.push(`主进程构建失败：${(err as Error).message}`)
    return finish()
  }

  // ── ② Renderer (multi-file ESM: entry + chunk-<hash>.mjs) ──────────────────
  let chunkRewrites = 0
  let hostRewrites = 0
  try {
    await esbuild.build({
      entryPoints: { renderer: rendererEntry },
      outdir: outDir,
      entryNames: 'renderer',
      chunkNames: 'chunk-[hash]',
      outExtension: { '.js': '.mjs' },
      bundle: true,
      // splitting must be on: without it the plugin's own dynamic imports are inlined into the
      // entry (the first screen then pays for heavy dependencies)
      splitting: true,
      platform: 'browser',
      format: 'esm',
      target: 'chrome120',
      jsx: 'automatic',
      plugins: [hostPlugin('renderer', draftRoot, specs)],
      loader: { '.css': 'css', '.svg': 'dataurl' },
      minify: !opts.dev,
      sourcemap: opts.dev ? 'inline' : false,
      logLevel: 'silent',
      legalComments: 'none'
    })
    // Order matters: first absolutize relative specifiers between chunks, then turn host
    // specifiers into bridge URLs (the former judges by the emitted file set, the latter only
    // looks at specifier shape)
    chunkRewrites = absolutizeChunkSpecifiers(id, outDir)
    hostRewrites = rewriteHostSpecifiersInBundle(outDir)
  } catch (err) {
    info.errors.push(...formatEsbuildErrors((err as { errors?: never[] }).errors))
    if (info.errors.length === 0) info.errors.push(`渲染层构建失败：${(err as Error).message}`)
    return finish()
  }

  // ── ③ Stylesheet (plugin.css) ─────────────────────────────────────────────
  const cssParts: string[] = []
  const scanned = scanDraftCandidates(draftRoot)
  if (cssMode === 'auto' && scanned.all.length > 0) {
    try {
      const generated = await compilePluginCss(scanned.all, host!.loader, draftRoot)
      appendCss(cssParts, generated)
    } catch (err) {
      info.warnings.push(
        `Tailwind 生成样式表失败（降级为不带样式）：${(err as Error).message}。` +
          `可以把 workshop.json 的 css 改成 'file' 并手写 plugin.css。`
      )
    }
  }
  const manualCss = path.join(draftRoot, 'plugin.css')
  if (cssMode !== 'off' && fs.existsSync(manualCss)) {
    appendCss(cssParts, fs.readFileSync(manualCss, 'utf-8'))
  } else if (cssMode === 'file' && !fs.existsSync(manualCss)) {
    info.warnings.push("css 模式是 'file'，但草稿里没有 plugin.css（产物将不含样式表）")
  }
  // esbuild css loader output: `import './x.css'` in plugin sources gets merged into plugin.css
  const emittedCss = path.join(outDir, 'renderer.css')
  if (fs.existsSync(emittedCss)) {
    appendCss(cssParts, fs.readFileSync(emittedCss, 'utf-8'))
    fs.rmSync(emittedCss, { force: true })
  }
  const finalCss = cssParts.join('\n\n')
  if (finalCss.trim()) {
    fs.writeFileSync(path.join(outDir, 'plugin.css'), finalCss + '\n', 'utf-8')
  }
  info.css = {
    mode: cssMode,
    bytes: Buffer.byteLength(finalCss, 'utf-8'),
    candidates: scanned.all.length,
    missing: missingClasses(finalCss, scanned.strict)
  }

  // ── ④ Manifest (entry is written by the build) ──
  const nextManifest: Record<string, unknown> = {
    ...raw,
    entry: { renderer: 'renderer.mjs', main: 'main.cjs' }
  }
  writeJson(path.join(outDir, 'plugin.json'), nextManifest)

  // ── ⑤ Main-process bare module check (anything detectable at build time must not wait
  // until load time) ─────────────────────────────────────────────────────────
  for (const spec of specs.mainSpecs) {
    if (spec.startsWith('@host/')) continue
    try {
      host!.loader.resolve(spec)
    } catch {
      info.warnings.push(
        `主进程依赖 '${spec}' 在宿主应用根解析不到：装载时会失败（可用宿主已有依赖，或改进 @host/main/** 桥）`
      )
    }
  }

  const files = listDraftFiles(id).length
  info.files = fs
    .readdirSync(outDir)
    .filter((f) => fs.statSync(path.join(outDir, f)).isFile())
    .map((f) => ({ path: f, size: fs.statSync(path.join(outDir, f)).size }))
    .sort((a, b) => a.path.localeCompare(b.path, 'en'))
  info.ok = true
  info.outDir = outDir
  info.at = Date.now()
  info.sourceHash = sourceHash
  if (chunkRewrites > 0) {
    info.warnings.push(
      `已把 ${chunkRewrites} 处产物内相对说明符改写为 plugin://${id}/…（blob import 前提）`
    )
  }
  if (hostRewrites > 0) {
    info.warnings.push(`已把 ${hostRewrites} 处宿主说明符改写为 plugin://host/ui.js 桥 URL`)
  }
  if (files === 0) info.warnings.push('草稿里一个文件都没有（异常状态）')

  // Update the "output fingerprint" only when writing into the real output directory: offline
  // tooling may build into a temporary outDir, and such a build does not mean dist/<id> was
  // updated (otherwise isBuildStale would misjudge an old output as the latest)
  if (path.resolve(outDir) === path.resolve(distDir(id))) {
    patchDraftMeta(id, { builtAt: info.at, sourceHash })
  }
  return finish()
}

/** Host specifiers the main process really resolves in the output (the acceptance battery checks the runtime table against this) */
export function bundleMainSpecs(outDir: string): string[] {
  const file = path.join(outDir, 'main.cjs')
  if (!fs.existsSync(file)) return []
  const code = fs.readFileSync(file, 'utf-8')
  const out = new Set<string>()
  const re = /__RB_HOST_RESOLVE__\(\s*(["'])((?:\\.|(?!\1)[^\\])*)\1\s*\)/g
  let match: RegExpExecArray | null
  while ((match = re.exec(code)) !== null) out.add(match[2])
  return [...out].sort()
}

/**
 * **Host UI keys** referenced by the renderer output (entry + all chunks, deduplicated).
 *
 * The output form is the build-time rewritten `plugin://host/ui.js?m=<key>` (see
 * `rewriteHostSpecifiersInBundle`), so decoding the `m=` parameter of the URL is enough; bare
 * host specifiers that were not rewritten cleanly are collected too — such leftovers make the
 * host loader fail to resolve outright, so acceptance must name them (marked with a `!` prefix).
 */
export function bundleRendererSpecs(outDir: string): string[] {
  const out = new Set<string>()
  const bareRe = /(\bfrom\s*|\bimport\s*\(\s*|(?:^|[;}\n])\s*import\s*)(['"])([^'"]+)\2/gm
  const bridgeRe = /plugin:\/\/host\/ui\.js\?m=([^"'\s)]+)/g
  for (const file of fs.readdirSync(outDir)) {
    if (!file.endsWith('.mjs')) continue
    const code = fs.readFileSync(path.join(outDir, file), 'utf-8')
    let match: RegExpExecArray | null
    bridgeRe.lastIndex = 0
    while ((match = bridgeRe.exec(code)) !== null) {
      try {
        out.add(decodeURIComponent(match[1]))
      } catch {
        out.add(match[1])
      }
    }
    bareRe.lastIndex = 0
    while ((match = bareRe.exec(code)) !== null) {
      const spec = match[3]
      if (spec.startsWith('@host/')) out.add(`!${spec}`)
      else if (RENDERER_VENDOR.some((v) => spec === v || spec.startsWith(v + '/'))) {
        out.add(`!@host/vendor/${spec}`)
      }
    }
  }
  return [...out].sort()
}

/** Whether the renderer output still has relative specifiers (guaranteed to fail under blob import → acceptance names them) */
export function relativeSpecifiersInBundle(outDir: string): string[] {
  const out: string[] = []
  for (const file of fs.readdirSync(outDir)) {
    if (!file.endsWith('.mjs')) continue
    const code = fs.readFileSync(path.join(outDir, file), 'utf-8')
    const re = /(\bfrom\s*|\bimport\s*\(\s*|(?:^|[;}\n])\s*import\s*)(['"])(\.{1,2}\/[^'"]+)\2/gm
    let match: RegExpExecArray | null
    while ((match = re.exec(code)) !== null) out.push(`${file} → ${match[3]}`)
  }
  return out
}
