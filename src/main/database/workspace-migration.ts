import { app } from 'electron'
import { dirname, join, resolve } from 'path'
import type { PGlite } from '@electric-sql/pglite'
import { and, asc, eq, sql } from 'drizzle-orm'
import logger from 'electron-log'
import { ormForClient, type Orm } from './orm'
import { agent_config, harness_topic, workspace } from './schema'

export interface WorkspaceMigrationResult {
  /** Active workspace id determined after migration; null means there is no workspace at all (waiting for the user to configure one on the chat page) */
  activeWorkspaceId: number | null
  /** Directory path of the active workspace (written back to settings together with the id to avoid inconsistency) */
  activeWorkspacePath: string | null
}

/** Default workspace path auto-generated by older versions (under Documents; users explicitly disliked it, so recognize and roll it back) */
function legacyAutoPath(): string {
  return join(app.getPath('documents'), 'RytenBench 工作区')
}

/** Default workspace path auto-generated by older versions (under userData; now changed to "do not auto-create workspaces") */
function legacyUserDataAutoPath(): string {
  return join(app.getPath('userData'), 'workspaces', 'default')
}

/**
 * Roll back the "default workspace" auto-created by older versions (idempotent).
 *
 * The app no longer creates workspaces automatically on startup, so the two default workspaces
 * generated historically need to be removed, returning the user to the "workspace not configured"
 * state where the chat page guides configuration.
 * Delete a workspace only when it has **no sessions and no agent config**, to avoid deleting one the user actually uses.
 */
async function revertAutoCreatedWorkspace(db: Orm, path: string, label: string): Promise<void> {
  const found = await db
    .select({
      id: workspace.id,
      topics: sql<number>`(SELECT COUNT(*)::int FROM ${harness_topic} t WHERE t.workspace_id = ${workspace.id})`,
      agents: sql<number>`(SELECT COUNT(*)::int FROM ${agent_config} a WHERE a.workspace_id = ${workspace.id})`
    })
    .from(workspace)
    .where(and(eq(workspace.name, '默认工作区'), eq(workspace.path, path)))
    .orderBy(asc(workspace.id))
    .limit(1)

  const row = found[0]
  if (!row) return
  if (row.topics > 0 || row.agents > 0) {
    logger.info(
      `[WorkspaceMigration] Keep ${label} default workspace id=${row.id} (topics=${row.topics}, agents=${row.agents})`
    )
    return
  }
  await db.delete(workspace).where(eq(workspace.id, row.id))
  logger.info(`[WorkspaceMigration] Reverted ${label} auto-created default workspace id=${row.id}`)
}

/**
 * Classify the historical batch of **plugin workspaces** in place from the default 'user' to 'plugin' (idempotent; only has an effect the first time it runs).
 *
 * Why it is needed: `workspace.kind` was only added in migration 0010, so plugin workspaces in old databases are all the default value; if they are
 * not recognized, they leak into the sidebar's "Work" list (user requirement on 2026-09-28: "plugin directories must not enter the 'Work' list").
 * The criterion must be consistent with the runtime one (`listPluginWorkspaces`): **a direct child directory of the plugin source root**.
 *
 * Why put it in the core startup migration instead of at plugin install time: this is a one-off data move that
 * needs a single UPDATE; doing it here guarantees "the first launch of the new version is already correct" without
 * waiting for the assistant plugin to have been opened.
 * Only `kind` is touched, not name or path (nor is updated_at refreshed — it drives sidebar sorting, and a move should not push rows to the top).
 */
async function classifyLegacyPluginWorkspaces(db: Orm, pluginsRoot?: string): Promise<void> {
  if (!pluginsRoot) return
  const root = resolve(pluginsRoot)
  const rows = await db
    .select({ id: workspace.id, path: workspace.path })
    .from(workspace)
    .where(eq(workspace.kind, 'user'))
  let classified = 0
  for (const row of rows) {
    if (!row.path) continue
    const resolved = resolve(row.path)
    // Case-insensitive (Windows): compare parent directories with both sides lowercased
    if (dirname(resolved).toLowerCase() !== root.toLowerCase()) continue
    await db.update(workspace).set({ kind: 'plugin' }).where(eq(workspace.id, row.id))
    classified += 1
  }
  if (classified > 0) {
    logger.info(`[WorkspaceMigration] Classified ${classified} legacy plugin workspace(s)`)
  }
}

/**
 * Workspace data migration (runs at startup, idempotent):
 * 1. Roll back the "default workspace" auto-created by older versions (Documents path and userData path once each,
 *    only when they have no sessions and no agent config);
 * 2. Classify historical plugin workspaces (`kind` = 'plugin', see above);
 * 3. Determine the active workspace: keep the activeWorkspaceId from settings (if it still exists), otherwise take the first one;
 *    return null when there is no workspace at all — the app no longer creates one automatically, so the chat page guides the user to pick a directory.
 *
 * Note: documents / knowledge base / todos are already global data (no workspace_id column) and take no part in any backfill or ownership handling.
 */
export async function migrateWorkspaceData(
  client: PGlite,
  getActiveWorkspaceId: () => number | undefined,
  /** Plugin storage path (used to classify historical plugin workspaces; unset = skip that step) */
  pluginsRoot?: string
): Promise<WorkspaceMigrationResult> {
  const db = ormForClient(client)

  await revertAutoCreatedWorkspace(db, legacyAutoPath(), 'legacy-documents')
  await revertAutoCreatedWorkspace(db, legacyUserDataAutoPath(), 'legacy-userData')
  await classifyLegacyPluginWorkspaces(db, pluginsRoot)

  // Determine the active workspace (do not create one)
  const workspaces = await db
    .select({ id: workspace.id, path: workspace.path })
    .from(workspace)
    .orderBy(asc(workspace.created_at), asc(workspace.id))

  if (workspaces.length === 0) {
    logger.info('[WorkspaceMigration] No workspace configured — waiting for user setup')
    return { activeWorkspaceId: null, activeWorkspacePath: null }
  }

  const storedActive = getActiveWorkspaceId()
  const stored = workspaces.find((w) => w.id === storedActive) ?? workspaces[0]
  return { activeWorkspaceId: stored.id, activeWorkspacePath: stored.path }
}
