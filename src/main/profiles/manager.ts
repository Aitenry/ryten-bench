import * as fs from 'node:fs'
import * as path from 'node:path'
import { createHash } from 'node:crypto'

/**
 * Account-level local data space (WeChat-style "switch account = switch local data container").
 *
 * Background: install records and plugin snapshots are isolated per account **on the platform**
 * (`hub_plugin_installs` primary key `(user_id, plugin_id)`), but the client's local side has always
 * been "one copy per machine": the same `RytenBenchDB`, `plugin-state/` and `lattice-sync.json` are
 * shared by all accounts. Switching accounts produced cross-talk accidents like "account B sees A's
 * ledger and pushes A's data to B's cloud".
 *
 * Model:
 * - **Machine level** (does not change with the account): `lattice-session.json` (login state),
 *   base URL, plugin packages, logs;
 * - **Account level** (managed by this file): `RytenBenchDB/`, `plugin-state/`, `lattice-sync.json`;
 * - the account data in use always sits at the userData root (the paths hardcoded by the DB /
 *   plugins need no change), and other accounts' data sleeps in `userData/profiles/<key>/`;
 *   switching accounts = swapping the two directory sets;
 * - not logged in = an independent `anonymous` container: plugin data from the logged-out period
 *   stays in the local space and is **not** merged into any account later (strict isolation).
 *
 * Safety measures:
 * - write a journal (`profiles/.switch.json`) before the swap, and resume/roll back from it at
 *   startup;
 * - the swap itself relies only on atomic renames of "root directory + container directory" and
 *   copies no data; it is invoked in two places: early startup (before the DB opens and plugins
 *   load, `runtime.ts`) and **in-place switching at runtime** (`live.ts`: stop streams/sync/DB,
 *   unload plugins, then swap, reconnect, refresh the window);
 * - abnormal states (source and target both exist) are neither merged nor overwritten: the extra
 *   copy is moved to `profiles/.orphan/<timestamp>/` for manual recovery, and a conflict is
 *   recorded.
 *
 * This module deliberately does not depend on electron: `userDataDir` is passed in by the caller,
 * so plain Node can unit-test it.
 */

/** Container key of the logged-out account */
export const ANONYMOUS_PROFILE = 'anonymous'

/**
 * Data swapped between accounts (order does not matter; directories or files both supported).
 *
 * Only **plugin-related** data goes here: plugin tables live in RytenBenchDB, plugin settings/state
 * in `plugin-state/`, and sync cursors in `lattice-sync.json`. AI conversations (`chat/`), file
 * history (`file-history/`) etc. are still machine-level shared for now; to isolate them too, add
 * the directory name to this array (whole directories are renamed at startup, exactly like the
 * existing entries).
 */
export const PROFILE_ITEMS = ['RytenBenchDB', 'plugin-state', 'lattice-sync.json'] as const
export type ProfileItem = (typeof PROFILE_ITEMS)[number]

const PROFILES_DIR = 'profiles'
const MARKER_FILE = '.active.json'
const JOURNAL_FILE = '.switch.json'
const ORPHAN_DIR = '.orphan'
const SESSION_FILE = 'lattice-session.json'

/** Container keys allow only safe characters (keys are generated by this module; this is one more layer of protection) */
const KEY_PATTERN = /^[A-Za-z0-9._-]{1,80}$/

/**
 * On Windows, a directory that was "just closed" may still have unreleased handles (PGlite worker /
 * antivirus scan / indexer), and rename fails with EBUSY / EPERM / EACCES. This timing is common
 * when switching the account data space at runtime, so back off and retry a few times; the backoff
 * uses a synchronous sleep - the caller is going to suspend the main process for this short period
 * anyway (the UI is about to be covered by the refresh), which beats a single rename failure
 * sending the user back to "restart the app".
 */
const RENAME_RETRIES = 4
const RENAME_RETRY_BASE_MS = 80
const RETRYABLE_RENAME_CODES = new Set(['EBUSY', 'EPERM', 'EACCES', 'ENOTEMPTY'])

function sleepSync(ms: number): void {
  const shared = new Int32Array(new SharedArrayBuffer(4))
  Atomics.wait(shared, 0, 0, ms)
}

function renameWithRetry(from: string, to: string): void {
  let lastError: unknown = null
  for (let attempt = 0; attempt <= RENAME_RETRIES; attempt += 1) {
    try {
      fs.renameSync(from, to)
      return
    } catch (err) {
      lastError = err
      const code = (err as NodeJS.ErrnoException).code ?? ''
      if (!RETRYABLE_RENAME_CODES.has(code) || attempt === RENAME_RETRIES) break
      sleepSync(RENAME_RETRY_BASE_MS * (attempt + 1))
    }
  }
  throw lastError
}

/** Minimal identity read from `lattice-session.json` (the refresh token is not decrypted) */
export interface SessionIdentity {
  /**
   * The file has a non-empty refresh token (= this machine considers itself logged in). Kept
   * distinct from `userId`: an old session may have only the token, not the user id yet.
   */
  loggedIn: boolean
  userId: string | null
  username?: string | null
  baseUrl?: string | null
}

/** `profiles/.active.json`: **which key the current root data belongs to** */
export interface ProfileMarker {
  version: 1
  key: string
  userId?: string | null
  username?: string | null
  baseUrl?: string | null
  updatedAt: number
}

/** `profiles/.switch.json`: an unfinished directory swap */
export interface ProfileJournal {
  version: 1
  from: string
  to: string
  /** `out` = root data has not been moved into from yet; `in` = the to data is being moved back to the root */
  stage: 'out' | 'in'
  startedAt: number
}

export interface ApplyProfileResult {
  /** The key in effect after applying */
  key: string
  /** The key before applying (`null` = first run, the root data is claimed by this key) */
  from: string | null
  /** Whether this call really changed the data layout / wrote the marker */
  changed: boolean
  /** Whether an interrupted switch was recovered */
  recovered: boolean
  /** On first run the root already had data, claimed by the current key (nothing moved) */
  claimedExisting: boolean
  /** Items actually moved this time */
  moved: ProfileItem[]
  /** Abnormal conflicts (the corresponding items were moved to `.orphan/`) */
  conflicts: ProfileItem[]
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function exists(target: string): boolean {
  try {
    fs.accessSync(target)
    return true
  } catch {
    return false
  }
}

function ensureDir(dir: string): void {
  fs.mkdirSync(dir, { recursive: true })
}

function readJson(file: string): unknown {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf-8')) as unknown
  } catch {
    return null
  }
}

/** Write JSON atomically (tmp + rename), so a half-written marker/journal does not derail the next startup */
function writeJsonAtomic(file: string, value: unknown): void {
  ensureDir(path.dirname(file))
  const tmp = `${file}.tmp`
  fs.writeFileSync(tmp, `${JSON.stringify(value, null, 2)}\n`, 'utf-8')
  fs.renameSync(tmp, file)
}

function assertKey(key: string): void {
  if (!KEY_PATTERN.test(key)) throw new Error(`非法的账号数据空间 key: ${key}`)
}

/* ────────────────────────────── paths ────────────────────────────── */

export function profilesRoot(userDataDir: string): string {
  return path.join(userDataDir, PROFILES_DIR)
}

export function profileDir(userDataDir: string, key: string): string {
  assertKey(key)
  return path.join(profilesRoot(userDataDir), key)
}

export function profileMarkerPath(userDataDir: string): string {
  return path.join(profilesRoot(userDataDir), MARKER_FILE)
}

export function profileJournalPath(userDataDir: string): string {
  return path.join(profilesRoot(userDataDir), JOURNAL_FILE)
}

export function profileSessionPath(userDataDir: string): string {
  return path.join(userDataDir, SESSION_FILE)
}

/* ────────────────────────────── identity / key ────────────────────────────── */

/**
 * Read the login identity (only the plaintext parts; whether the refresh token is decryptable is
 * not handled here).
 *
 * As long as the file has no non-empty refresh token, it is treated as "not logged in" - avoiding
 * keeping data under the old account after the token was cleared.
 */
export function readSessionIdentity(userDataDir: string): SessionIdentity {
  const raw = readJson(profileSessionPath(userDataDir))
  if (!isRecord(raw)) return { loggedIn: false, userId: null }
  const token = typeof raw.refreshToken === 'string' ? raw.refreshToken : ''
  if (token === '') return { loggedIn: false, userId: null }
  const user = isRecord(raw.user) ? raw.user : null
  const rawId = user && typeof user.id === 'string' ? user.id.trim() : ''
  const username = user && typeof user.username === 'string' ? user.username : null
  const baseUrl = typeof raw.baseUrl === 'string' ? raw.baseUrl : null
  return { loggedIn: true, userId: rawId === '' ? null : rawId, username, baseUrl }
}

/**
 * Account -> local container key.
 *
 * It includes a hash of the base URL: different Lattice nodes may have the same user id and must
 * not share a container. No user id (logged out / old session not yet filled in) -> `anonymous`.
 */
export function deriveProfileKey(identity: SessionIdentity): string {
  const userId = (identity.userId ?? '').trim()
  if (userId === '') return ANONYMOUS_PROFILE
  const baseUrl = (identity.baseUrl ?? '').trim()
  const digest = createHash('sha256').update(`${baseUrl}\n${userId}`).digest('hex').slice(0, 16)
  return `u-${digest}`
}

/* ────────────────────────────── marker / journal ────────────────────────────── */

export function readProfileMarker(userDataDir: string): ProfileMarker | null {
  const raw = readJson(profileMarkerPath(userDataDir))
  if (!isRecord(raw)) return null
  if (raw.version !== 1) return null
  if (typeof raw.key !== 'string' || !KEY_PATTERN.test(raw.key)) return null
  return {
    version: 1,
    key: raw.key,
    userId: typeof raw.userId === 'string' ? raw.userId : null,
    username: typeof raw.username === 'string' ? raw.username : null,
    baseUrl: typeof raw.baseUrl === 'string' ? raw.baseUrl : null,
    updatedAt: typeof raw.updatedAt === 'number' ? raw.updatedAt : 0
  }
}

export function writeProfileMarker(
  userDataDir: string,
  key: string,
  identity?: SessionIdentity
): void {
  assertKey(key)
  const marker: ProfileMarker = {
    version: 1,
    key,
    userId: identity?.userId ?? null,
    username: identity?.username ?? null,
    baseUrl: identity?.baseUrl ?? null,
    updatedAt: Date.now()
  }
  ensureDir(profileDir(userDataDir, key))
  writeJsonAtomic(profileMarkerPath(userDataDir), marker)
}

function readProfileJournal(userDataDir: string): ProfileJournal | null {
  const raw = readJson(profileJournalPath(userDataDir))
  if (!isRecord(raw)) return null
  if (raw.version !== 1) return null
  if (typeof raw.from !== 'string' || !KEY_PATTERN.test(raw.from)) return null
  if (typeof raw.to !== 'string' || !KEY_PATTERN.test(raw.to)) return null
  if (raw.stage !== 'out' && raw.stage !== 'in') return null
  return {
    version: 1,
    from: raw.from,
    to: raw.to,
    stage: raw.stage,
    startedAt: typeof raw.startedAt === 'number' ? raw.startedAt : 0
  }
}

function writeProfileJournal(userDataDir: string, journal: ProfileJournal): void {
  writeJsonAtomic(profileJournalPath(userDataDir), journal)
}

function clearProfileJournal(userDataDir: string): void {
  try {
    fs.rmSync(profileJournalPath(userDataDir), { force: true })
  } catch {
    // A journal that cannot be deleted does not affect correctness: the next startup replays from the marker state
  }
}

/* ────────────────────────────── moving ────────────────────────────── */

/**
 * Abnormal conflict: the same data exists in both the "root directory" and the "target container".
 *
 * No merge, no delete: the **extra copy** (the path given by the caller) is moved into
 * `.orphan/<timestamp>/`, keeping the original file name so it can be recovered manually.
 */
function moveToOrphan(userDataDir: string, sourcePath: string): string {
  const stamp = `${Date.now()}-${Math.random().toString(36).slice(2, 8)}`
  const orphanDir = path.join(profilesRoot(userDataDir), ORPHAN_DIR, stamp)
  ensureDir(orphanDir)
  const dest = path.join(orphanDir, path.basename(sourcePath))
  renameWithRetry(sourcePath, dest)
  return dest
}

function noteMoved(moved: ProfileItem[], item: ProfileItem): void {
  if (!moved.includes(item)) moved.push(item)
}

/** Root directory -> an account container (switch out); idempotent: already moved items are not moved again */
function drainToProfile(
  userDataDir: string,
  key: string,
  moved: ProfileItem[],
  conflicts: ProfileItem[]
): void {
  const dir = profileDir(userDataDir, key)
  ensureDir(dir)
  for (const item of PROFILE_ITEMS) {
    const source = path.join(userDataDir, item)
    if (!exists(source)) continue
    const dest = path.join(dir, item)
    if (exists(dest)) {
      // This can only appear in abnormal/manually modified directories: the root copy is "live",
      // the container copy is old
      moveToOrphan(userDataDir, dest)
      conflicts.push(item)
    }
    renameWithRetry(source, dest)
    noteMoved(moved, item)
  }
}

/** An account container -> root directory (switch in); idempotent: already moved-in items are not moved again */
function fillFromProfile(
  userDataDir: string,
  key: string,
  moved: ProfileItem[],
  conflicts: ProfileItem[]
): void {
  ensureDir(userDataDir)
  const dir = profileDir(userDataDir, key)
  ensureDir(dir)
  for (const item of PROFILE_ITEMS) {
    const source = path.join(dir, item)
    if (!exists(source)) continue
    const dest = path.join(userDataDir, item)
    if (exists(dest)) {
      // The root already has an entry with the same name: it should not appear in the current
      // layout; move it to orphan and take the container one as authoritative
      moveToOrphan(userDataDir, dest)
      conflicts.push(item)
    }
    renameWithRetry(source, dest)
    noteMoved(moved, item)
  }
}

/** Recover an interrupted switch (continue per the journal's stage; idempotent in both directions) */
function resumeSwitch(
  userDataDir: string,
  journal: ProfileJournal,
  moved: ProfileItem[],
  conflicts: ProfileItem[]
): void {
  if (journal.from !== journal.to) {
    if (journal.stage === 'out') {
      drainToProfile(userDataDir, journal.from, moved, conflicts)
      writeProfileJournal(userDataDir, { ...journal, stage: 'in' })
    }
    fillFromProfile(userDataDir, journal.to, moved, conflicts)
  }
  // Write the marker before deleting the journal: even if the marker write fails, the next run
  // replays from the journal
  writeProfileMarker(userDataDir, journal.to)
  clearProfileJournal(userDataDir)
}

/* ────────────────────────────── main entry ────────────────────────────── */

/**
 * Make the root directory the data space of `desiredKey` (called early at app startup, before
 * DB/plugin loading).
 *
 * Three cases:
 * 1. there is an unfinished switch -> resume it first;
 * 2. first run (no marker) -> existing root data is claimed by `desiredKey` (nothing moved);
 * 3. marker differs from desired -> swap the two directory sets.
 */
export function applyProfile(
  userDataDir: string,
  desiredKey: string,
  identity?: SessionIdentity
): ApplyProfileResult {
  assertKey(desiredKey)
  ensureDir(userDataDir)
  ensureDir(profilesRoot(userDataDir))
  ensureDir(profileDir(userDataDir, desiredKey))

  const result: ApplyProfileResult = {
    key: desiredKey,
    from: null,
    changed: false,
    recovered: false,
    claimedExisting: false,
    moved: [],
    conflicts: []
  }

  // (1) Resume the switch left unfinished last time
  const journal = readProfileJournal(userDataDir)
  if (journal) {
    resumeSwitch(userDataDir, journal, result.moved, result.conflicts)
    result.recovered = true
  }

  const marker = readProfileMarker(userDataDir)

  // (2) First run: root data belongs to the current desired key (after an upgrade the user's
  // existing data is neither lost nor moved)
  if (!marker) {
    const hasExisting = PROFILE_ITEMS.some((item) => exists(path.join(userDataDir, item)))
    writeProfileMarker(userDataDir, desiredKey, identity)
    result.changed = true
    result.claimedExisting = hasExisting
    return result
  }

  // (3) Already in the target space: nothing to do
  if (marker.key === desiredKey) {
    result.from = marker.key
    return result
  }

  // (4) Swap: root (old account) -> profiles/from, profiles/to -> root
  const from = marker.key
  writeProfileJournal(userDataDir, {
    version: 1,
    from,
    to: desiredKey,
    stage: 'out',
    startedAt: Date.now()
  })
  drainToProfile(userDataDir, from, result.moved, result.conflicts)
  writeProfileJournal(userDataDir, {
    version: 1,
    from,
    to: desiredKey,
    stage: 'in',
    startedAt: Date.now()
  })
  fillFromProfile(userDataDir, desiredKey, result.moved, result.conflicts)
  writeProfileMarker(userDataDir, desiredKey, identity)
  clearProfileJournal(userDataDir)

  result.from = from
  result.changed = true
  return result
}
