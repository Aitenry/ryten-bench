/**
 * Update-source abstraction.
 *
 * The update *engine* (download, checksum verification, installer hand-off) is electron-updater;
 * what changes when the app moves from GitHub Releases to Lattice is **where the update feed lives**.
 * An `UpdateSource` resolves that feed. The rest of the app (service, IPC, renderer) never imports
 * a concrete source.
 *
 * Lattice can expose the same electron-builder `latest.yml` layout at a generic URL initially.
 * Besides the standard installer fields, that manifest should carry `contentSha256` (SHA-256 of
 * the packaged app.asar) so same-version rebuilds can be detected as content updates. If it later
 * needs authentication or a different manifest, add a custom electron-updater provider and return
 * its `UpdateFeed` here — the service and the UI stay unchanged.
 */

export type UpdateFeed =
  | {
      provider: 'github'
      owner: string
      repo: string
      private?: boolean
      token?: string
    }
  | {
      provider: 'generic'
      url: string
      channel?: string
      useMultipleRangeRequest?: boolean
      requestHeaders?: Record<string, string>
    }

export interface UpdateSource {
  /** Diagnostic id exposed in AppUpdateState.source. */
  readonly id: string
  /** Human-readable name (logs only; renderer copy is translated independently). */
  readonly label: string
  readonly allowPrerelease?: boolean
  resolveFeed(): Promise<UpdateFeed>
}

/**
 * Current production source: GitHub Releases of this repository.
 *
 * electron-updater reads the release's `latest.yml` (generated by electron-builder), verifies the
 * installer's sha512, then downloads only the changed blocks when possible. The owner/repo can be
 * overridden for forks or staging builds without touching code.
 */
export class GitHubUpdateSource implements UpdateSource {
  readonly id = 'github'
  readonly label = 'GitHub Releases'
  readonly allowPrerelease = false

  constructor(
    private readonly owner = process.env.RYTENBENCH_GITHUB_OWNER?.trim() || 'Aitenry',
    private readonly repo = process.env.RYTENBENCH_GITHUB_REPO?.trim() || 'ryten-bench'
  ) {}

  async resolveFeed(): Promise<UpdateFeed> {
    return {
      provider: 'github',
      owner: this.owner,
      repo: this.repo
    }
  }
}

/**
 * Future Lattice source. It speaks the same channel layout as electron-updater's generic provider:
 * the base URL must serve `latest.yml` / `latest-mac.yml` / `latest-linux.yml` plus the installers.
 *
 * This class is already selectable for staging (`RYTENBENCH_UPDATE_SOURCE=lattice` +
 * `RYTENBENCH_LATTICE_UPDATE_URL=...`) so the switch can be tested before Lattice is live.
 */
export class LatticeUpdateSource implements UpdateSource {
  readonly id = 'lattice'
  readonly label = 'Lattice'
  readonly allowPrerelease = false

  constructor(
    private readonly baseUrl: string,
    private readonly requestHeaders?: Record<string, string>
  ) {}

  async resolveFeed(): Promise<UpdateFeed> {
    return {
      provider: 'generic',
      url: this.baseUrl,
      useMultipleRangeRequest: false,
      requestHeaders: this.requestHeaders
    }
  }
}

/**
 * Pick the active update source once at service startup.
 *
 * The default stays GitHub. Lattice can be enabled by environment for staging; later this can read
 * a persisted setting / account-aware selection with no change to the rest of the feature.
 */
export function createUpdateSource(): UpdateSource {
  const requested = process.env.RYTENBENCH_UPDATE_SOURCE?.trim().toLowerCase()
  if (requested === 'lattice') {
    const baseUrl = process.env.RYTENBENCH_LATTICE_UPDATE_URL?.trim()
    if (!baseUrl) {
      throw new Error('RYTENBENCH_UPDATE_SOURCE=lattice requires RYTENBENCH_LATTICE_UPDATE_URL')
    }
    return new LatticeUpdateSource(baseUrl)
  }
  return new GitHubUpdateSource()
}
